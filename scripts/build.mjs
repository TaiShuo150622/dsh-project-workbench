import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const client = (await Promise.all(['client/continuity.js', 'client/app.js'].map(path => readFile(new URL(path, root), 'utf8')))).join('\n');
const config = JSON.parse(await readFile(new URL('config/hyperparams.yaml', root), 'utf8'));
const limits = Object.fromEntries(Object.entries(config).map(([key, v]) => [key, v.value]));
const hash = createHash('sha256');
for (const path of ['client/continuity.js', 'client/app.js', 'index.js', 'server/store.js', 'server/native.js', 'server/projects.js', 'server/continuity.js', 'server/worktrees.js', 'config/hyperparams.yaml']) hash.update(await readFile(new URL(path, root)));
const id = hash.digest('hex').slice(0, 12);
await writeFile(new URL('client.js', root), `// Generated by scripts/build.mjs.\nwindow.__ModuleLoader__.load({id:'dsh-project-workbench',factory:(require)=>{\nconst React=require('react');const h=React.createElement;const LIMITS=${JSON.stringify(limits)};const BUILD=${JSON.stringify(id)};\n${client}\nreturn {inject,apply};}});\n`);
await writeFile(new URL('build.json', root), JSON.stringify({ id }, null, 2) + '\n');
console.log(`Built ${id}`);
